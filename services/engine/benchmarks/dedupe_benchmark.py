"""Phase B1 — benchmark for fuzzy duplicate detection (BUILD-SPRINT B1,
BLUEPRINT §12 T3).

Grades `app/engine/relations.py` against planted ground truth on two datasets:

- the hand-written fixture `tests/fixtures/dirty_names.csv` (truth in
  `dirty_names_truth.json`), which includes deliberate look-alike
  non-duplicates;
- a larger synthetic set (a few hundred rows, one seed): random
  name/address/city entities, a share of which get 1-2 corrupted copies
  (typos, case/whitespace, "Last, First" order, address abbreviations,
  punctuation, city spelling).

Metrics are pair-level: every pair of rows inside one predicted group is a
predicted pair, every pair inside one true entity is a true pair. Also
reported: how many pairs blocking hands to the scorer versus all n*(n-1)/2
(blocking efficiency) and the share of true pairs blocking keeps (blocking
recall). The linker never sees the truth; it is used only to grade.

Run from services/engine/:

    python -m benchmarks.dedupe_benchmark              # seed 42
    python -m benchmarks.dedupe_benchmark --seed 7

Every number is computed in the run; the report holds no timestamps or
timings, so the same seed and library versions rewrite it byte for byte.
"""
from __future__ import annotations

import argparse
import json
import platform
import random
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

import pandas as pd

ENGINE_ROOT = Path(__file__).resolve().parents[1]
if str(ENGINE_ROOT) not in sys.path:  # lets `python benchmarks/dedupe_benchmark.py` find `app`
    sys.path.insert(0, str(ENGINE_ROOT))

from app.engine.parse import infer_types, parse_csv_bytes  # noqa: E402
from app.engine.relations import (  # noqa: E402
    MATCH_THRESHOLD, MIN_COLUMN_SIM, candidate_pair_set, find_duplicates)

DEFAULT_SEED = 42
GENERATED_ENTITIES = 300
DUPLICATE_SHARE = 0.30       # share of entities that get corrupted copies
FIXTURE_DIR = ENGINE_ROOT / "tests" / "fixtures"
RESULTS_PATH = ENGINE_ROOT / "benchmarks" / "results" / "dedupe_benchmark.md"
GENERATED_MARKER = ("<!-- Generated by benchmarks/dedupe_benchmark.py - "
                    "do not edit by hand; re-run the script. -->")

FIRST = ["Aarav", "Aditi", "Amit", "Ananya", "Arjun", "Bhavna", "Chetan", "Deepa",
         "Farhan", "Gita", "Harish", "Isha", "Jatin", "Kavya", "Lalit", "Meera",
         "Nikhil", "Omkar", "Pooja", "Rahul", "Sneha", "Tarun", "Usha", "Vivek",
         "Yash", "Zoya", "Rohit", "Priya", "Anil", "Sunita", "Manoj", "Rekha"]
LAST = ["Sharma", "Verma", "Gupta", "Iyer", "Nair", "Reddy", "Patel", "Singh",
        "Kumar", "Joshi", "Mehta", "Rao", "Das", "Bose", "Khan", "Shah",
        "Menon", "Pillai", "Desai", "Kapoor", "Malhotra", "Bhatt", "Saxena", "Mishra"]
STREETS = ["Park Street", "MG Road", "Nehru Road", "Station Road", "Lake View Apartments",
           "Gandhi Lane", "Temple Street", "Hill Road", "Residency Road", "Market Avenue",
           "Garden Lane", "Church Street", "Civil Lines", "Ring Road", "Beach Road"]
CITIES = ["Delhi", "Mumbai", "Pune", "Chennai", "Kolkata", "Jaipur", "Lucknow",
          "Hyderabad", "Bengaluru", "Ahmedabad"]
CITY_ALIASES = {"Bengaluru": "Bangalore", "Mumbai": "Bombay", "Kolkata": "Calcutta"}
ADDRESS_VARIANTS = {"Road": "Rd.", "Street": "St", "Lane": "Ln", "Apartments": "Apt",
                    "Avenue": "Ave"}


# --- synthetic dirty data ------------------------------------------------------

def _typo(text: str, rng: random.Random) -> str:
    """One character-level edit (swap/drop/duplicate/substitute) inside a word."""
    if len(text) < 4:
        return text
    pos = rng.randrange(1, len(text) - 1)  # never the first letter: users rarely typo it
    if text[pos] == " " or text[pos - 1] == " ":
        return text
    kind = rng.choice(["swap", "drop", "dup", "sub"])
    if kind == "swap":
        return text[:pos] + text[pos + 1] + text[pos] + text[pos + 2:]
    if kind == "drop":
        return text[:pos] + text[pos + 1:]
    if kind == "dup":
        return text[:pos] + text[pos] + text[pos:]
    return text[:pos] + rng.choice("aeiou") + text[pos + 1:]


def corrupt(name: str, address: str, city: str, rng: random.Random) -> tuple[str, str, str]:
    """A realistic dirty copy of one record: 1-3 independent corruptions."""
    ops = rng.sample(["name_typo", "case", "pad", "swap", "abbrev", "city_alias",
                      "address_typo", "punct"], k=rng.choice([1, 2, 2, 3]))
    for op in ops:
        if op == "name_typo":
            name = _typo(name, rng)
        elif op == "case":
            name, city = rng.choice([(name.lower(), city.lower()), (name.upper(), city),
                                     (name, city.upper())])
        elif op == "pad":
            name, city = f" {name}", f"{city} "
        elif op == "swap":
            first, _, last = name.partition(" ")
            name = f"{last}, {first}"
        elif op == "abbrev":
            for full, short in ADDRESS_VARIANTS.items():
                address = address.replace(full, short)
        elif op == "city_alias":
            city = CITY_ALIASES.get(city, city.lower())
        elif op == "address_typo":
            address = _typo(address, rng)
        elif op == "punct":
            address = address.replace("MG", "M.G.").replace(" ", "  ", 1)
    return name, address, city


def generate_dirty_set(seed: int, n_entities: int = GENERATED_ENTITIES
                       ) -> tuple[pd.DataFrame, list[int]]:
    """Synthetic dirty-names frame and the entity id of every row."""
    rng = random.Random(seed)
    records: list[tuple[int, str, str, str]] = []
    for ent in range(n_entities):
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        address = f"{rng.randrange(1, 300)} {rng.choice(STREETS)}"
        city = rng.choice(CITIES)
        records.append((ent, name, address, city))
        if rng.random() < DUPLICATE_SHARE:
            for _ in range(rng.choice([1, 1, 2])):
                records.append((ent, *corrupt(name, address, city, rng)))
    rng.shuffle(records)
    df = pd.DataFrame({
        "customer_id": [f"C{i:05d}" for i in range(len(records))],
        "name": [r[1] for r in records], "address": [r[2] for r in records],
        "city": [r[3] for r in records]})
    return df, [r[0] for r in records]


# --- grading ---------------------------------------------------------------------

def pairs_from_groups(groups: list[list[int]]) -> set[tuple[int, int]]:
    return {p for g in groups for p in combinations(sorted(g), 2)}


def truth_pairs(entities: list) -> set[tuple[int, int]]:
    by_entity: dict = {}
    for i, e in enumerate(entities):
        by_entity.setdefault(e, []).append(i)
    return pairs_from_groups([m for m in by_entity.values() if len(m) > 1])


def grade(df: pd.DataFrame, entities: list) -> dict:
    """Run the linker on `df` and grade it against `entities` (row -> entity)."""
    types = infer_types(df)
    result = find_duplicates(df, types)
    predicted = pairs_from_groups([g["rows"] for g in result["groups"]])
    truth = truth_pairs(entities)
    tp = len(predicted & truth)
    precision = tp / len(predicted) if predicted else 1.0
    recall = tp / len(truth) if truth else 1.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    candidates = candidate_pair_set(df, types)
    stats = result["stats"]
    return {
        "rows": len(df), "true_pairs": len(truth), "predicted_pairs": len(predicted),
        "tp": tp, "fp": len(predicted - truth), "fn": len(truth - predicted),
        "precision": precision, "recall": recall, "f1": f1,
        "clusters": result["duplicate_groups"],
        "true_clusters": sum(c > 1 for c in Counter(entities).values()),
        "naive_pairs": stats["naive_pairs"], "candidate_pairs": len(candidates),
        "blocking_reduction": 1 - len(candidates) / stats["naive_pairs"],
        "blocking_recall": len(truth & candidates) / len(truth) if truth else 1.0,
        "false_positive_pairs": sorted(predicted - truth)[:10],
        "missed_pairs": sorted(truth - predicted)[:10],
    }


def load_fixture() -> tuple[pd.DataFrame, list]:
    raw = (FIXTURE_DIR / "dirty_names.csv").read_bytes()
    truth = json.loads((FIXTURE_DIR / "dirty_names_truth.json").read_text(encoding="utf-8"))
    return parse_csv_bytes(raw), truth["entities"]


# --- report -----------------------------------------------------------------------

def render(seed: int, fixture: dict, generated: dict) -> str:
    def row(label: str, r: dict) -> str:
        return (f"| {label} | {r['rows']} | {r['true_pairs']} | {r['predicted_pairs']} | "
                f"{r['precision']:.4f} | {r['recall']:.4f} | {r['f1']:.4f} | "
                f"{r['clusters']} / {r['true_clusters']} |")

    def block(label: str, r: dict) -> str:
        return (f"| {label} | {r['rows']} | {r['naive_pairs']:,} | {r['candidate_pairs']:,} | "
                f"{r['blocking_reduction'] * 100:.2f}% | {r['blocking_recall']:.4f} |")

    def errors(label: str, r: dict) -> str:
        return (f"- **{label}:** {r['fp']} false-positive pair(s) "
                f"{r['false_positive_pairs'] or ''}, {r['fn']} missed pair(s) "
                f"{r['missed_pairs'] or ''}")

    gen_label = f"Generated (seed {seed}, {GENERATED_ENTITIES} entities)"
    return "\n".join([
        "# Fuzzy dedupe benchmark", "", GENERATED_MARKER, "",
        "Every number on this page was measured by "
        "`services/engine/benchmarks/dedupe_benchmark.py` in the run described below.",
        "Nothing here is typed in by hand.", "",
        "## Setup", "",
        f"- **Linker:** `app/engine/relations.py` (blocking, rapidfuzz token-sort + Jaro-Winkler + "
        f"weakest-word score, union-find clustering). Match threshold {MATCH_THRESHOLD}, "
        f"per-column floor {MIN_COLUMN_SIM}.",
        "- **Fixture:** `tests/fixtures/dirty_names.csv`, hand-written, with look-alike "
        "non-duplicates (same name different address, same address and surname different "
        "first name, close first names). The thresholds were tuned while building this "
        "fixture, so treat its row as a regression check, not a generalisation estimate.",
        f"- **Generated set:** seed {seed}; {GENERATED_ENTITIES} random name/address/city "
        f"entities, {int(DUPLICATE_SHARE * 100)}% of them get 1-2 corrupted copies "
        "(typos, case/whitespace, \"Last, First\", abbreviations, punctuation, city "
        "aliases). Random names collide, so look-alike non-duplicates occur naturally. "
        "Never used for tuning.",
        "- **Pair metrics:** every pair of rows inside a predicted group is a predicted pair; "
        "every pair inside a true entity is a true pair.",
        "- **Blocking efficiency:** candidate pairs handed to the scorer vs all "
        "n*(n-1)/2 row pairs. **Blocking recall:** share of true pairs that blocking keeps.",
        f"- **Environment:** Python {platform.python_version()}, pandas {pd.__version__}.", "",
        "## Pair quality", "",
        "| Dataset | Rows | True pairs | Predicted pairs | Pair precision | Pair recall | "
        "Pair F1 | Clusters (found / true) |",
        "|:--|--:|--:|--:|--:|--:|--:|--:|",
        row("Fixture (dirty_names.csv)", fixture), row(gen_label, generated), "",
        errors("Fixture", fixture), errors("Generated", generated), "",
        "## Blocking efficiency", "",
        "| Dataset | Rows examined | All row pairs | Candidate pairs after blocking | "
        "Reduction | Blocking recall |",
        "|:--|--:|--:|--:|--:|--:|",
        block("Fixture (dirty_names.csv)", fixture), block(gen_label, generated), "",
    ])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = parser.parse_args(argv)

    fixture = grade(*load_fixture())
    generated = grade(*generate_dirty_set(args.seed))
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text(render(args.seed, fixture, generated), encoding="utf-8")
    for label, r in (("fixture", fixture), ("generated", generated)):
        print(f"{label}: precision={r['precision']:.4f} recall={r['recall']:.4f} "
              f"f1={r['f1']:.4f} clusters={r['clusters']} "
              f"candidates={r['candidate_pairs']}/{r['naive_pairs']}")
    print(f"wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
