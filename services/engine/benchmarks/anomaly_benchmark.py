def _environment() -> dict[str, str]:
    import sklearn
    import torch
    return {"Python": platform.python_version(), "numpy": np.__version__,
            "scikit-learn": sklearn.__version__, "torch": str(torch.__version__)}


def run_benchmark(dataset: Dataset, seed: int = DEFAULT_SEED,
                  threshold: float = DEFAULT_THRESHOLD) -> dict:
    """Score a labelled dataset with every detector and the ensemble, then grade it.

    The rows take the product's own path: `robust_scale` -> `score_matrix`.
    A single detector flags a row when its calibrated score >= threshold; the
    ensemble uses the product's `flag_mask`. Output: a plain dict (dataset
    summary, seed, threshold, weights, per-model metrics, acceptance verdict,
    library versions) holding everything `render_markdown` prints.
    """
    labels = np.asarray(dataset.labels, dtype=bool)
    _require_both_classes(labels, dataset.name)
    scored = score_matrix(robust_scale(dataset.values), seed=seed)
    scores = scored["scores"]
    flags = {model: scores[model] >= threshold for model in MODELS}
    flags[ENSEMBLE] = flag_mask(scores, threshold)
    metrics = {model: evaluate(labels, flags[model], scores[model]) for model in REPORT_ORDER}
    return {
        "dataset": {
            "key": dataset.key,
            "name": dataset.name,
            "rows": int(labels.size),
            "features": int(dataset.values.shape[1]),
            "anomalies": int(np.count_nonzero(labels)),
            "notes": list(dataset.notes),
            "is_fallback": dataset.fallback_reason is not None,
        },
        "seed": int(seed),
        "threshold": float(threshold),
        "weights": {model: float(scored["weights"][model]) for model in MODELS},
        "metrics": metrics,
        "acceptance": check_acceptance(metrics),
        "environment": _environment(),
    }


