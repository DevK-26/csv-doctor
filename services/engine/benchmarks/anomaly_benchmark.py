def precision_recall_f1(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    """Precision, recall and F1 from confusion counts (0.0 when undefined)."""
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * tp / (2 * tp + fp + fn) if tp else 0.0
    return precision, recall, f1


def auroc(labels: np.ndarray, scores: np.ndarray) -> float:
    """Area under the ROC curve via the rank-sum (Mann-Whitney) identity.

    Equals the probability that a randomly chosen anomaly scores higher than
    a randomly chosen normal row, with ties counted as half. Inputs: bool
    labels (True = anomaly) and one score per row (higher = more anomalous).
    """
    truth = np.asarray(labels, dtype=bool).ravel()
    values = np.asarray(scores, dtype=np.float64).ravel()
    if truth.shape != values.shape:
        raise ValueError(f"AUROC needs one score per label; got {values.size} scores "
                         f"for {truth.size} labels")
    positives = int(np.count_nonzero(truth))
    negatives = int(truth.size - positives)
    if positives == 0 or negatives == 0:
        raise ValueError("AUROC needs at least one anomaly and one normal row")
    if not np.isfinite(values).all():
        raise ValueError("AUROC scores must be finite")
    # Tied scores share the average of the ranks they occupy, which is what
    # makes a tie between an anomaly and a normal row count as half a win.
    _, inverse, counts = np.unique(values, return_inverse=True, return_counts=True)
    last_rank = np.cumsum(counts)
    average_rank = last_rank - (counts - 1) / 2.0
    rank_sum = float(average_rank[inverse][truth].sum())
    return (rank_sum - positives * (positives + 1) / 2.0) / (positives * negatives)


def evaluate(labels: np.ndarray, flagged: np.ndarray, scores: np.ndarray) -> dict:
    """Grade one detector against the ground truth.

    Inputs: bool labels (True = anomaly), the detector's bool flags and its
    continuous scores. Output: precision, recall, f1 (from the flags), auroc
    (from the scores) and the counts behind them: flagged, tp, fp, fn.
    """
    truth = np.asarray(labels, dtype=bool).ravel()
    flags = np.asarray(flagged, dtype=bool).ravel()
    if truth.shape != flags.shape:
        raise ValueError(f"need one flag per label; got {flags.size} flags "
                         f"for {truth.size} labels")
    tp = int(np.count_nonzero(flags & truth))
    fp = int(np.count_nonzero(flags & ~truth))
    fn = int(np.count_nonzero(~flags & truth))
    precision, recall, f1 = precision_recall_f1(tp, fp, fn)
    return {"precision": precision, "recall": recall, "f1": f1,
            "auroc": auroc(truth, scores),
            "flagged": tp + fp, "tp": tp, "fp": fp, "fn": fn}


def check_acceptance(metrics: dict) -> dict:
    """BUILD-SPRINT A2 acceptance: the ensemble beats at least one single model on F1.

    F1 is compared at the precision the report prints, so the verdict can be
    checked against the published table; a tie is not a win.
    Output: {"passed": bool, "beaten": [model, ...]}.
    """
    shown = {model: round(metrics[model]["f1"], METRIC_DECIMALS) for model in REPORT_ORDER}
    beaten = [model for model in MODELS if shown[ENSEMBLE] > shown[model]]
    return {"passed": bool(beaten), "beaten": beaten}


