# `shuttle.tst`; the second is the repository's zip of the whole dataset.
SHUTTLE_PAGE = "https://archive.ics.uci.edu/dataset/148/statlog+shuttle"
SHUTTLE_URLS = (
    "https://archive.ics.uci.edu/ml/machine-learning-databases/statlog/shuttle/shuttle.tst",
    "https://archive.ics.uci.edu/static/public/148/statlog+shuttle.zip",
)
SHUTTLE_FILE = "shuttle.tst"
SHUTTLE_TEST_ROWS = 14_500  # size of the test split as documented by the dataset
SHUTTLE_ATTRIBUTES = 9
SHUTTLE_CLASSES = (1, 2, 3, 4, 5, 6, 7)
SHUTTLE_NORMAL_CLASS = 1
SHUTTLE_DISCARDED_CLASS = 4
DOWNLOAD_TIMEOUT = 30.0
MAX_DOWNLOAD_BYTES = 20 * 1024 * 1024

SYNTHETIC_ROWS = 5_000
SYNTHETIC_MIN_ROWS = 200
SYNTHETIC_ANOMALY_FRACTION = 0.05
SYNTHETIC_FEATURES = 8
SYNTHETIC_FACTORS = 3
SYNTHETIC_NOISE = 0.3


class DatasetError(RuntimeError):
    """The benchmark dataset could not be obtained or failed validation."""


@dataclass(frozen=True, eq=False)
class Dataset:
    """A labelled benchmark dataset.

    `values` is float64 [rows, features], unscaled; `labels` is bool [rows]
    with True = anomaly; `notes` are provenance lines copied into the report;
    `fallback_reason` is set only when synthetic data stood in for a failed
    download.
    """
    key: str
    name: str
    values: np.ndarray
    labels: np.ndarray
    notes: tuple[str, ...]
    fallback_reason: str | None = None


def _require_both_classes(labels: np.ndarray, what: str) -> None:
    anomalies = int(np.count_nonzero(labels))
    if anomalies == 0 or anomalies == len(labels):
        raise DatasetError(f"{what} needs both normal and anomalous rows; "
                           f"found {anomalies} anomalies in {len(labels)} rows")


# --------------------------------------------------------------------------
# Public dataset: Statlog (Shuttle)
# --------------------------------------------------------------------------

def parse_shuttle(raw: bytes) -> np.ndarray:
    """Parse the Statlog (Shuttle) text layout into an integer table.

    Input: file bytes, one row per line: 9 integer attributes then the class
    (1-7), separated by spaces (commas are accepted too).
    Output: int64 array [rows, 10]. Raises DatasetError naming the first bad
    line, so an HTML error page or a truncated file is never mistaken for data.
    """
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise DatasetError("Shuttle file is not plain ASCII text - "
                           "the download is not the dataset") from exc
    width = SHUTTLE_ATTRIBUTES + 1
    rows: list[list[int]] = []
    for number, line in enumerate(text.splitlines(), start=1):
        tokens = line.replace(",", " ").split()
        if not tokens:
            continue
        if len(tokens) != width:
            raise DatasetError(f"Shuttle file line {number}: expected {width} values, "
                               f"found {len(tokens)}")
        try:
            rows.append([int(token) for token in tokens])
        except ValueError as exc:
            raise DatasetError(f"Shuttle file line {number}: every value must be "
                               "an integer") from exc
    if not rows:
        raise DatasetError("Shuttle file contains no data rows")
    try:
        table = np.asarray(rows, dtype=np.int64)
    except OverflowError as exc:
        raise DatasetError("Shuttle file holds a value too large to be real data") from exc
    unknown = sorted(set(table[:, -1].tolist()) - set(SHUTTLE_CLASSES))
    if unknown:
        raise DatasetError(f"Shuttle file has unknown class label(s) {unknown}; "
                           f"expected {SHUTTLE_CLASSES[0]}-{SHUTTLE_CLASSES[-1]}")
    return table


def shuttle_anomaly_task(table: np.ndarray) -> tuple[np.ndarray, np.ndarray, int]:
    """Turn the 7-class Shuttle table into the usual anomaly-detection task.

    Class 1 is normal, class 4 is discarded, every other class is an anomaly.
    Output: (values float64 [rows, 9], labels bool [rows], rows discarded).
    """
    classes = table[:, -1]
    keep = classes != SHUTTLE_DISCARDED_CLASS
    values = table[keep, :-1].astype(np.float64)
    labels = classes[keep] != SHUTTLE_NORMAL_CLASS
    return values, labels, int(np.count_nonzero(~keep))


def _shuttle_dataset(raw: bytes) -> Dataset:
    table = parse_shuttle(raw)
    if len(table) != SHUTTLE_TEST_ROWS:
        raise DatasetError(f"Shuttle test split must have {SHUTTLE_TEST_ROWS} rows, found "
                           f"{len(table)} - the download is truncated or the wrong file")
    values, labels, discarded = shuttle_anomaly_task(table)
    _require_both_classes(labels, "the Shuttle anomaly task")
    anomaly_classes = ", ".join(str(c) for c in SHUTTLE_CLASSES
                                if c not in (SHUTTLE_NORMAL_CLASS, SHUTTLE_DISCARDED_CLASS))
    notes = (
        f"Source: {SHUTTLE_PAGE} - file `{SHUTTLE_FILE}`, downloaded by the script "
        f"(SHA-256 `{hashlib.sha256(raw).hexdigest()}`).",
        f"The file has {len(table):,} rows. Class {SHUTTLE_NORMAL_CLASS} is normal, class "
        f"{SHUTTLE_DISCARDED_CLASS} ({discarded:,} rows) is discarded and classes "
        f"{anomaly_classes} are anomalies - the usual anomaly-detection framing of this "
        "dataset.",
        "Only the test split is used: the training split is published as a Unix-compress "
        "`.Z` archive, which Python's standard library cannot read.",
    )
    return Dataset(key="shuttle",
                   name=f"Statlog (Shuttle), test split `{SHUTTLE_FILE}` - "
                        "UCI Machine Learning Repository",
                   values=values, labels=labels, notes=notes)


def _http_get(url: str, timeout: float) -> bytes:
    """Download one URL into memory, refusing anything over MAX_DOWNLOAD_BYTES."""
    with urllib.request.urlopen(url, timeout=timeout) as response:
        payload = response.read(MAX_DOWNLOAD_BYTES + 1)
    if len(payload) > MAX_DOWNLOAD_BYTES:
        raise DatasetError(f"download is larger than {MAX_DOWNLOAD_BYTES:,} bytes")
    return payload


def _zip_member(payload: bytes, name: str) -> bytes:
    """Read one file (matched by name, in any folder) out of an in-memory zip."""
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        for info in archive.infolist():
            if info.filename.rsplit("/", 1)[-1] == name:
                if info.file_size > MAX_DOWNLOAD_BYTES:
                    raise DatasetError(f"{name} inside the archive is larger than "
                                       f"{MAX_DOWNLOAD_BYTES:,} bytes")
                return archive.read(info)
    raise DatasetError(f"archive has no file named {name}")


def load_shuttle(data_dir: Path, timeout: float = DOWNLOAD_TIMEOUT) -> Dataset:
    """Statlog (Shuttle) test split as an anomaly task, from the cache or UCI.

    Input: cache directory. A valid cached copy is used without touching the
    network; otherwise each URL in SHUTTLE_URLS is tried in order and the
    first file that passes validation is cached. Raises DatasetError listing
    every failure if none works.
    """
    cache = Path(data_dir) / "shuttle" / SHUTTLE_FILE
    if cache.is_file():
        try:
            return _shuttle_dataset(cache.read_bytes())
        except (OSError, DatasetError) as exc:
            print(f"warning: ignoring unusable cache file {cache}: {exc}", file=sys.stderr)
    failures = []
    for url in SHUTTLE_URLS:
        try:
            payload = _http_get(url, timeout)
            raw = _zip_member(payload, SHUTTLE_FILE) if url.endswith(".zip") else payload
            dataset = _shuttle_dataset(raw)
        except (OSError, http.client.HTTPException, zipfile.BadZipFile, DatasetError) as exc:
            failures.append(f"{url}: {type(exc).__name__}: {exc}")
            continue
        try:
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_bytes(raw)
        except OSError as exc:  # a read-only checkout must not block the benchmark
            print(f"warning: could not cache the dataset at {cache}: {exc}", file=sys.stderr)
        return dataset
    raise DatasetError("could not obtain Statlog (Shuttle) - " + "; ".join(failures))


# --------------------------------------------------------------------------
# Synthetic fallback
# --------------------------------------------------------------------------

def make_synthetic_dataset(seed: int, rows: int | None = None,
                           fallback_reason: str | None = None) -> Dataset:
    """Deterministic labelled dataset generated in code (the offline fallback).

    Inputs: `seed`; `rows` (default SYNTHETIC_ROWS, 5% of them anomalies).
    Normal rows follow a low-rank linear structure: 3 hidden factors mixed
    into 8 correlated features, plus Gaussian noise. Three anomaly types are
    planted in equal shares, chosen because each is the hard case for a
    different detector family:
    - global: far outside the usual range of every feature;
    - dependency: every feature inside its usual range, but the relationship
      between features is broken (each column drawn independently);
    - clustered: a tight group of rows sitting away from the normal data.
    Output: a Dataset with shuffled rows.
    """
    rows = SYNTHETIC_ROWS if rows is None else int(rows)
    if rows < SYNTHETIC_MIN_ROWS:
        raise DatasetError(f"the synthetic dataset needs at least {SYNTHETIC_MIN_ROWS} rows, "
                           f"got {rows}")
    rng = np.random.default_rng(seed)
    features, factors = SYNTHETIC_FEATURES, SYNTHETIC_FACTORS
    n_anomalies = int(round(rows * SYNTHETIC_ANOMALY_FRACTION))
    n_normal = rows - n_anomalies
    n_global = n_anomalies // 3
    n_dependency = n_anomalies // 3
    n_clustered = n_anomalies - n_global - n_dependency

    loadings = rng.normal(size=(factors, features))

    def structured(count: int) -> np.ndarray:
        hidden = rng.normal(size=(count, factors))
        return hidden @ loadings + SYNTHETIC_NOISE * rng.normal(size=(count, features))

    normal = structured(n_normal)
    spread = normal.std(axis=0)

    global_rows = rng.uniform(-6.0, 6.0, size=(n_global, features)) * spread
    donors = structured(n_dependency)
    dependency_rows = np.column_stack([rng.permutation(donors[:, j]) for j in range(features)])
    centre = 4.0 * spread * rng.choice([-1.0, 1.0], size=features)
    clustered_rows = centre + 0.1 * spread * rng.normal(size=(n_clustered, features))

    values = np.vstack([normal, global_rows, dependency_rows, clustered_rows])
    labels = np.zeros(rows, dtype=bool)
    labels[n_normal:] = True
    order = rng.permutation(rows)  # so the anomalies are not all at the end of the file
    notes = (
        f"Generated in code by `make_synthetic_dataset(seed={seed})` - nothing is downloaded.",
        f"Normal rows: {n_normal:,}, built from {factors} hidden factors mixed into "
        f"{features} correlated features plus Gaussian noise.",
        f"Planted anomalies: {n_global} global (far outside the usual range of every "
        f"feature), {n_dependency} dependency (each feature in range, but the relationship "
        f"between features is broken) and {n_clustered} clustered (a tight group away from "
        "the normal data).",
    )
    return Dataset(key="synthetic", name="Synthetic dataset generated by the benchmark script",
                   values=values[order], labels=labels[order], notes=notes,
                   fallback_reason=fallback_reason)


def load_dataset(name: str, seed: int, data_dir: Path = DEFAULT_DATA_DIR) -> Dataset:
    """Resolve a dataset choice: "auto", "shuttle" or "synthetic".

    "auto" uses Shuttle (cache, then download) and falls back to the synthetic
    dataset if it cannot be obtained, announcing the fallback on stderr.
    "shuttle" raises DatasetError instead of falling back.
    """
    if name == "synthetic":
        return make_synthetic_dataset(seed)
    if name not in ("auto", "shuttle"):
        raise DatasetError(f"unknown dataset {name!r}; choose auto, shuttle or synthetic")
    try:
        return load_shuttle(data_dir)
    except DatasetError as exc:
        if name == "shuttle":
            raise
        print(f"WARNING: {exc}\nWARNING: falling back to the SYNTHETIC dataset - the report "
              "will not contain public-dataset numbers.", file=sys.stderr)
        return make_synthetic_dataset(seed, fallback_reason=str(exc))


