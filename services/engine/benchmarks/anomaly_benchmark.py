"""Phase A2 — benchmark harness for the anomaly ensemble (BUILD-SPRINT A2,
BLUEPRINT §12 T2 "a real evaluation").

What it does: takes a dataset whose anomalies are already labelled, scores it
with the exact code path the product runs on an uploaded CSV
(`robust_scale` -> `score_matrix` -> `flag_mask`), grades Isolation Forest,
Local Outlier Factor, the autoencoder and the ensemble against the labels,
and writes Precision / Recall / F1 / AUROC per model to
`benchmarks/results/anomaly_benchmark.md`. The models never see the labels;
they are only used afterwards to grade the output.

Run it from services/engine/:

    python -m benchmarks.anomaly_benchmark                      # seed 42
    python -m benchmarks.anomaly_benchmark --dataset shuttle    # no fallback
    python -m benchmarks.anomaly_benchmark --dataset synthetic  # no download

Dataset: Statlog (Shuttle) from the UCI Machine Learning Repository — the
test split `shuttle.tst` (14,500 rows, 9 numeric attributes, 7 classes),
downloaded on first use and cached under `benchmarks/data/` (git-ignored,
never vendored). It becomes the usual anomaly task: class 1 is normal,
class 4 is discarded, classes 2/3/5/6/7 are anomalies.

Synthetic fallback: if every download attempt fails, `--dataset auto` (the
default) falls back to `make_synthetic_dataset` — data generated in code
with three planted anomaly types — and the report says so in a banner at
the top. Synthetic numbers are a smoke test of the harness, not evidence
about real data; `--dataset shuttle` fails loudly instead of falling back.

Determinism: one seed drives the models and the synthetic generator, and
the report holds no timestamps or timings, so the same seed on the same
data and library versions rewrites the file byte for byte.
"""
