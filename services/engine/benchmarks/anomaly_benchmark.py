# Report
# --------------------------------------------------------------------------

def fmt_metric(value: float) -> str:
    """The one number format used for every metric in the report."""
    return f"{value:.{METRIC_DECIMALS}f}"


def render_markdown(result: dict) -> str:
    """Render a `run_benchmark` result as the Markdown report.

    Pure function of its input: no clock, no I/O, ASCII only, so the same
    result always renders to the same bytes.
    """
    data = result["dataset"]
    metrics = result["metrics"]
    acceptance = result["acceptance"]
    threshold = f"{result['threshold']:g}"
    weights = ", ".join(f"{MODEL_LABELS[m]} {result['weights'][m]:.3f}" for m in MODELS)
    environment = ", ".join(f"{name} {version}" for name, version in result["environment"].items())
    anomaly_pct = 100.0 * data["anomalies"] / data["rows"]
    shown_f1 = {model: fmt_metric(metrics[model]["f1"]) for model in REPORT_ORDER}

    lines = [
        "# Anomaly detection benchmark",
        "",
        GENERATED_MARKER,
        "",
        "Every number on this page was measured by",
        "`services/engine/benchmarks/anomaly_benchmark.py` in the run described below.",
        "Nothing here is typed in by hand.",
        "",
    ]
    if data["key"] == "synthetic":
        cause = ("The public dataset could not be downloaded, so this run fell back to"
                 if data["is_fallback"] else
                 "This run was asked (`--dataset synthetic`) to use")
        lines += [
            f"> **SYNTHETIC DATA - not a public-dataset result.** {cause}",
            "> the synthetic dataset built into the script. These numbers are a smoke test",
            "> of the harness; do not quote them as a real-world benchmark. Re-run with",
            "> network access and `--dataset shuttle` for the public-dataset numbers.",
            "",
        ]
    lines += [
        "## Dataset",
        "",
        f"- **Dataset:** {data['name']}",
        f"- **Rows scored:** {data['rows']:,} ({data['anomalies']:,} labelled anomalies, "
        f"{anomaly_pct:.2f}%)",
        f"- **Features:** {data['features']} numeric",
    ]
    lines += [f"- {note}" for note in data["notes"]]
    lines += [
        "",
        "## Results",
        "",
        "| Model | Precision | Recall | F1 | AUROC | Flagged | TP | FP | FN |",
        "|:--|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for model in REPORT_ORDER:
        row = metrics[model]
        label = f"**{ENSEMBLE_LABEL}**" if model == ENSEMBLE else MODEL_LABELS[model]
        cells = [label,
                 *(fmt_metric(row[key]) for key in ("precision", "recall", "f1", "auroc")),
                 *(str(row[key]) for key in ("flagged", "tp", "fp", "fn"))]
        lines.append("| " + " | ".join(cells) + " |")
    lines += [
        "",
        f"- Seed: {result['seed']}. Flag threshold: {threshold}. Ensemble weights: {weights}.",
        f"- Environment: {environment}.",
        "",
        "## How the numbers are computed",
        "",
        "- The rows take the same path as an uploaded CSV: `robust_scale` ->",
        "  `score_matrix` in `app/engine/anomalies.py`. The models never see the labels;",
        "  the labels are only used afterwards to grade the output.",
        f"- A single detector flags a row when its calibrated score is >= {threshold}",
        f"  ({FLAG_Z:g} robust standard deviations above the median row).",
        "- The ensemble flags a row with the product's own rule (`flag_mask`): the",
        f"  weighted-average score is >= {threshold} and at least 2 of the 3 detectors",
        "  flag it.",
        "- Flagged = TP + FP. Precision = TP / (TP + FP), Recall = TP / (TP + FN),",
        "  F1 = 2 TP / (2 TP + FP + FN). A detector that flags nothing gets precision 0.",
        "- AUROC is threshold-free: the probability that a randomly chosen anomaly gets a",
        "  higher calibrated score than a randomly chosen normal row (ties count half).",
        "",
        "## Acceptance check (BUILD-SPRINT A2)",
        "",
        "Criterion: the ensemble beats at least one single model on F1, compared at the",
        f"{METRIC_DECIMALS} decimals shown in the table.",
        "",
    ]
    if acceptance["passed"]:
        beaten = ", ".join(f"{MODEL_LABELS[m]} ({shown_f1[m]})" for m in acceptance["beaten"])
        lines.append(f"**PASS** - ensemble F1 {shown_f1[ENSEMBLE]} beats {beaten}.")
    else:
        singles = ", ".join(f"{MODEL_LABELS[m]} {shown_f1[m]}" for m in MODELS)
        lines.append(f"**FAIL** - ensemble F1 {shown_f1[ENSEMBLE]} does not beat any single "
                     f"model ({singles}).")
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "cd services/engine",
        f"python -m benchmarks.anomaly_benchmark --seed {result['seed']} "
        f"--dataset {data['key']}",
        "```",
        "",
    ]
    return "\n".join(lines)


def write_report(text: str, path: Path) -> None:
    """Write the report as UTF-8 with LF line endings, creating parent folders."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point.

    Returns the exit code: 0 = report written and the acceptance check passed,
    1 = report written but the ensemble beat no single model, 2 = no dataset
    could be obtained (only with `--dataset shuttle`).
    """
    parser = argparse.ArgumentParser(
        prog="python -m benchmarks.anomaly_benchmark",
        description="Benchmark the anomaly detectors and the ensemble on labelled data.")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED,
                        help="seed for the models and the synthetic generator "
                             "(default: %(default)s)")
    parser.add_argument("--dataset", choices=("auto", "shuttle", "synthetic"), default="auto",
                        help="auto: Shuttle, with the synthetic fallback if it cannot be "
                             "downloaded (default); shuttle: fail instead of falling back; "
                             "synthetic: skip the download")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="where to write the Markdown report (default: %(default)s)")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR,
                        help="download cache directory (default: %(default)s)")
    args = parser.parse_args(argv)

    try:
        dataset = load_dataset(args.dataset, seed=args.seed, data_dir=args.data_dir)
    except DatasetError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    result = run_benchmark(dataset, seed=args.seed)
    report = render_markdown(result)
    write_report(report, args.output)
    print(report)
    print(f"Report written to {args.output}")
    if not result["acceptance"]["passed"]:
        print("Acceptance check FAILED: the ensemble did not beat any single model on F1.",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
