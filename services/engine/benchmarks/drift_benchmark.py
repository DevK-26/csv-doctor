"""Phase A3 — benchmark harness for the drift detectors (BUILD-SPRINT A3,
BLUEPRINT §12 T1 "drift detection delay").

What it does: builds a synthetic stream with a KNOWN drift point (a mean shift
at a stated sample index) and a no-drift control from the same generator,
then grades the hand-written detectors in `app/engine/drift.py` against the
planted truth:

- streaming: Page-Hinkley, ADWIN and WindowedDetector (PSI / KS / JS) are fed
  the stream one value at a time through `detect_stream`; the detection delay
  is the index of the first alarm minus the planted drift index (negative =
  a false early alarm, reported as such);
- batch: `compare_numeric` (PSI, KS, JS) compares the before-drift half with
  the after-drift half, and the two halves of the control stream.

The detectors never see the planted index; it is only used afterwards to
grade the alarms. Results go to `benchmarks/results/drift_benchmark.md`.

Run it from services/engine/:

    python -m benchmarks.drift_benchmark              # seed 42
    python -m benchmarks.drift_benchmark --seed 7     # another stream

Acceptance (the script exits 1 if it fails; the bar is fixed, see
MAX_DELAY): every streaming detector's first alarm on the drift stream lies
at or after the drift point and within MAX_DELAY samples of it, none of them
alarms on the control stream, and the batch comparison calls the drift
halves "significant" and the control halves "stable".

Determinism: one seed drives the generator, and the report holds no
timestamps or timings, so the same seed and library versions rewrite the
file byte for byte.
"""
from __future__ import annotations

import argparse
import platform
import sys
from pathlib import Path

import numpy as np

ENGINE_ROOT = Path(__file__).resolve().parents[1]
if str(ENGINE_ROOT) not in sys.path:  # lets `python benchmarks/drift_benchmark.py` find `app`
    sys.path.insert(0, str(ENGINE_ROOT))

from app.engine.drift import (  # noqa: E402
    ADWIN, PageHinkley, WindowedDetector, clip_to_fences, compare_numeric,
    detect_stream)

DEFAULT_SEED = 42
STREAM_LENGTH = 2000
DRIFT_INDEX = 1000      # first sample drawn from the shifted distribution
SHIFT = 1.5             # mean shift, in standard deviations of the base N(0, 1)
# Acceptance bar: "near the planted drift point" = within 10% of the stream
# length. Fixed on purpose - tune detector parameters, never this.
MAX_DELAY = STREAM_LENGTH // 10
METRIC_DECIMALS = 4
GENERATED_MARKER = ("<!-- Generated by benchmarks/drift_benchmark.py - "
                    "do not edit by hand; re-run the script. -->")

BENCHMARK_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT = BENCHMARK_DIR / "results" / "drift_benchmark.md"

DETECTOR_ORDER = ("page_hinkley", "adwin", "windowed_psi", "windowed_ks", "windowed_js")
DETECTOR_LABELS = {
    "page_hinkley": "Page-Hinkley",
    "adwin": "ADWIN",
    "windowed_psi": "WindowedDetector (PSI)",
    "windowed_ks": "WindowedDetector (KS)",
    "windowed_js": "WindowedDetector (JS)",
}


def make_streams(seed: int, length: int = STREAM_LENGTH, drift_index: int = DRIFT_INDEX,
                 shift: float = SHIFT) -> tuple[np.ndarray, np.ndarray]:
    """Return (drift stream, control stream) drawn from one seeded generator.

    Both are N(0, 1) noise. The drift stream's mean jumps by `shift` at
    `drift_index`; the control has the same noise and no jump.
    """
    rng = np.random.default_rng(seed)
    control = rng.normal(0.0, 1.0, size=length)
    drifted = rng.normal(0.0, 1.0, size=length)
    drifted[drift_index:] += shift
    return drifted, control


def make_detectors(value_range: float) -> dict:
    """Fresh detectors, in DETECTOR_ORDER.

    Parameters are the product defaults except where a comment says otherwise.
    ADWIN's `value_range` is the width of the stream's Tukey fences, exactly
    as the product's `find_change_points` supplies it.
    """
    return {
        "page_hinkley": PageHinkley(),
        "adwin": ADWIN(value_range=value_range),
        "windowed_psi": WindowedDetector("psi", window=200, step=10),
        "windowed_ks": WindowedDetector("ks", window=200, step=10),
        "windowed_js": WindowedDetector("js", window=200, step=10),
    }


def run_stream(values: np.ndarray) -> dict[str, list[int]]:
    """Alarm indices (in order) of every detector over one stream.

    The stream is clipped to its own Tukey fences first, as the product does,
    so that a lone outlier cannot fake a drift.
    """
    clipped, width = clip_to_fences(values)
    return {name: [event["detected_at"] for event in detect_stream(clipped, detector)]
            for name, detector in make_detectors(width).items()}


def run_benchmark(seed: int = DEFAULT_SEED) -> dict:
    """Run every measurement; return plain data for `render_markdown`."""
    drifted, control = make_streams(seed)
    drift_alarms, control_alarms = run_stream(drifted), run_stream(control)

    streaming = []
    for name in DETECTOR_ORDER:
        alarms = drift_alarms[name]
        first = alarms[0] if alarms else None
        delay = None if first is None else first - DRIFT_INDEX
        streaming.append({
            "name": name,
            "first_alarm": first,
            "delay": delay,
            "alarms": alarms,
            "control_alarms": control_alarms[name],
            "near_drift": delay is not None and 0 <= delay <= MAX_DELAY,
            "quiet_on_control": not control_alarms[name],
        })

    batch = {
        "drift": compare_numeric(drifted[:DRIFT_INDEX], drifted[DRIFT_INDEX:]),
        "control": compare_numeric(control[:DRIFT_INDEX], control[DRIFT_INDEX:]),
    }
    batch_ok = batch["drift"]["level"] == "significant" and batch["control"]["level"] == "stable"
    passed = batch_ok and all(row["near_drift"] and row["quiet_on_control"] for row in streaming)
    return {"seed": seed, "streaming": streaming, "batch": batch,
            "acceptance": {"passed": passed, "batch_ok": batch_ok}}


def _alarm_list(alarms: list[int]) -> str:
    return ", ".join(str(a) for a in alarms) if alarms else "none"


def render_markdown(result: dict) -> str:
    """The Markdown report for a `run_benchmark` result. No timestamps, no timings."""
    seed = result["seed"]
    d = METRIC_DECIMALS
    lines = [
        "# Drift detection benchmark",
        "",
        GENERATED_MARKER,
        "",
        "Every number on this page was measured by",
        "`services/engine/benchmarks/drift_benchmark.py` in the run described below.",
        "Nothing here is typed in by hand.",
        "",
        "## Setup",
        "",
        f"- **Seed:** {seed} (one `numpy.random.default_rng` drives both streams).",
        f"- **Stream length:** {STREAM_LENGTH:,} samples of N(0, 1) noise.",
        f"- **Planted drift:** at sample index **{DRIFT_INDEX}** (0-based, first shifted sample) "
        f"the mean jumps by +{SHIFT} standard deviations (N(0, 1) to N({SHIFT}, 1)).",
        f"- **Control:** a second stream from the same generator with no jump.",
        "- Both streams are clipped to their own Tukey fences before the streaming detectors, "
        "as the product does.",
        f"- **Detection delay** = first alarm index minus planted drift index "
        f"(negative = false early alarm). Acceptance bar: 0 to {MAX_DELAY} samples "
        f"({MAX_DELAY / STREAM_LENGTH:.0%} of the stream).",
        "",
        "## Streaming detectors",
        "",
        "| Detector | Planted drift index | First alarm index | Detection delay (samples) "
        "| All alarms on drift stream | Alarms on control stream | Near drift | Quiet on control |",
        "|:--|--:|--:|--:|:--|:--|:--|:--|",
    ]
    for row in result["streaming"]:
        first = "none" if row["first_alarm"] is None else str(row["first_alarm"])
        delay = "missed" if row["delay"] is None else f"{row['delay']:+d}"
        lines.append(
            f"| {DETECTOR_LABELS[row['name']]} | {DRIFT_INDEX} | {first} | {delay} "
            f"| {_alarm_list(row['alarms'])} | {_alarm_list(row['control_alarms'])} "
            f"| {'yes' if row['near_drift'] else 'NO'} "
            f"| {'yes' if row['quiet_on_control'] else 'NO'} |")
    lines += [
        "",
        "## Batch comparison (`compare_numeric`)",
        "",
        f"Samples 0-{DRIFT_INDEX - 1} against samples {DRIFT_INDEX}-{STREAM_LENGTH - 1} "
        "of each stream.",
        "",
        "| Stream | PSI | KS statistic | KS p-value | JS divergence (bits) | Level | Drifted |",
        "|:--|--:|--:|--:|--:|:--|:--|",
    ]
    for key, label in (("drift", "Drift stream (before vs after)"),
                       ("control", "Control stream (first half vs second half)")):
        b = result["batch"][key]
        lines.append(
            f"| {label} | {b['psi']:.{d}f} | {b['ks_statistic']:.{d}f} "
            f"| {b['ks_p_value']:.3g} | {b['js_divergence']:.{d}f} "
            f"| {b['level']} | {'yes' if b['drifted'] else 'no'} |")

    quiet = [DETECTOR_LABELS[r["name"]] for r in result["streaming"] if r["quiet_on_control"]]
    noisy = [DETECTOR_LABELS[r["name"]] for r in result["streaming"] if not r["quiet_on_control"]]
    control = result["batch"]["control"]
    lines += [
        "",
        "## Control stream outcome",
        "",
        f"- Quiet (no alarm in {STREAM_LENGTH:,} samples): {', '.join(quiet) if quiet else 'none'}.",
        f"- False alarms: {', '.join(noisy) if noisy else 'none'}.",
        f"- Batch halves: level `{control['level']}` (PSI {control['psi']:.{d}f}, "
        f"KS p-value {control['ks_p_value']:.3g}).",
        "",
        "## Acceptance",
        "",
        f"- Every detector alarmed within 0 to {MAX_DELAY} samples after the planted drift "
        f"and stayed quiet on the control; batch called the drift halves significant and the "
        f"control halves stable: **{'PASSED' if result['acceptance']['passed'] else 'FAILED'}**.",
        "",
        "## Environment",
        "",
        f"- Python {platform.python_version()}, numpy {np.__version__}.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "cd services/engine",
        f"python -m benchmarks.drift_benchmark --seed {seed}",
        "```",
        "",
    ]
    return "\n".join(lines)


def write_report(text: str, path: Path) -> None:
    """Write the report as UTF-8 with LF line endings, creating parent folders."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point.

    Returns the exit code: 0 = report written and acceptance passed,
    1 = report written but a detector missed, alarmed early or false-alarmed.
    """
    parser = argparse.ArgumentParser(
        prog="python -m benchmarks.drift_benchmark",
        description="Benchmark the drift detectors on a stream with a planted mean shift.")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED,
                        help="seed for the synthetic streams (default: %(default)s)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="where to write the Markdown report (default: %(default)s)")
    args = parser.parse_args(argv)

    result = run_benchmark(seed=args.seed)
    report = render_markdown(result)
    write_report(report, args.output)
    print(report)
    print(f"Report written to {args.output}")
    if not result["acceptance"]["passed"]:
        print("Acceptance check FAILED: see the table above.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
